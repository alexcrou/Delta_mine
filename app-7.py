def init_state():
    for key, value in {"profile_ready": False, "norms_ready": False, "rd_ready": False, "gp_ready": False}.items():
        st.session_state.setdefault(key, value)


def run_sequence(steps, seconds):
    bar = st.progress(0, text="Инициализация рабочего процесса…")
    for idx, label in enumerate(steps):
        with st.status(label, expanded=True) as status:
            st.write("Проверка и консолидация данных в рабочем контуре проекта.")
            ticks = seconds * 10
            for tick in range(ticks):
                time.sleep(0.1)
                bar.progress(int(((idx * ticks + tick + 1) / (len(steps) * ticks)) * 100), text=f"{label}…")
            status.update(label=f"{label} — завершено", state="complete", expanded=False)
    return bar


