def init_state() -> None:
    defaults = {
        "profile_loaded": False,
        "norms_updated": False,
        "roadmap": DEFAULT_ROADMAP.copy(),
        "budget": DEFAULT_BUDGET.copy(),
    }
    for key, value in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = value


def level_color(level: str) -> str:
    return {
        "Критический": "#d62728",
        "Высокий": "#f39c12",
        "Средний": "#2a9d8f",
    }.get(level, "#718096")


